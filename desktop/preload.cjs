const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('bigfishDesktop',Object.freeze({
  state:()=>ipcRenderer.invoke('bigfish:state'),
  connect:(url,token)=>ipcRenderer.invoke('bigfish:connect',{url,token}),
  request:(op,body)=>ipcRenderer.invoke('bigfish:request',{op,body}),
  preferences:()=>ipcRenderer.invoke('bigfish:preferences'),
  mutatePreferences:(ops,revision)=>ipcRenderer.invoke('bigfish:preferences-mutate',{ops,revision}),
  petRequest:(query,bytes)=>ipcRenderer.invoke('bigfish:pets',{query,bytes}),
  openSession:session=>ipcRenderer.invoke('bigfish:open-session',session),
  environment:()=>ipcRenderer.invoke('bigfish:environment'),
  configureDesktop:(value,revision,authorizeGeometry,launchAtLogin)=>ipcRenderer.invoke('bigfish:desktop-configure',{value,revision,authorizeGeometry,launchAtLogin}),
  configureVoice:value=>ipcRenderer.invoke('bigfish:voice-configure',value),
  microphone:()=>ipcRenderer.invoke('bigfish:microphone'),
  transcribe:(audio,mediaType)=>ipcRenderer.invoke('bigfish:transcribe',{audio,mediaType}),
  cancelTranscription:()=>ipcRenderer.invoke('bigfish:voice-cancel'),
  onHostChanged:callback=>{const fn=()=>callback();ipcRenderer.on('bigfish:host-changed',fn);return()=>ipcRenderer.removeListener('bigfish:host-changed',fn);},
  voiceDisplay:state=>ipcRenderer.send('bigfish:voice-display',state),
  onVoiceDisplay:callback=>{const fn=(_e,state)=>callback(state);ipcRenderer.on('bigfish:voice-display',fn);return()=>ipcRenderer.removeListener('bigfish:voice-display',fn);},
  onVoiceReset:callback=>{const fn=()=>callback();ipcRenderer.on('bigfish:voice-reset',fn);return()=>ipcRenderer.removeListener('bigfish:voice-reset',fn);},
  onGeometryGesture:callback=>{const fn=(_e,kind)=>callback(kind);ipcRenderer.on('bigfish:geometry-gesture',fn);return()=>ipcRenderer.removeListener('bigfish:geometry-gesture',fn);},
  dragState:active=>ipcRenderer.send('bigfish:drag-state',active),
  drag:(dx,dy)=>ipcRenderer.send('bigfish:drag',{dx,dy}),
  regions:regions=>ipcRenderer.send('bigfish:regions',regions),
  appearance:(size,enabled,preview=false)=>ipcRenderer.send('bigfish:appearance',{size,enabled,preview}),
  walkPolicy:policy=>ipcRenderer.send('bigfish:walk-policy',policy),
  onMotion:callback=>{const fn=(_e,motion)=>callback(motion);ipcRenderer.on('bigfish:motion',fn);return()=>ipcRenderer.removeListener('bigfish:motion',fn);},
  onMotionState:callback=>{const fn=(_e,frame)=>callback(frame);ipcRenderer.on('bigfish:motion-state',fn);return()=>ipcRenderer.removeListener('bigfish:motion-state',fn);},
  activityArea:()=>ipcRenderer.invoke('bigfish:activity-area'),
  configureActivityArea:(value,revision,displayId)=>ipcRenderer.invoke('bigfish:activity-area-configure',{value,revision,displayId}),
  onActivityArea:callback=>{const fn=()=>callback();ipcRenderer.on('bigfish:activity-area-changed',fn);return()=>ipcRenderer.removeListener('bigfish:activity-area-changed',fn);},
  settings:page=>{if(page===undefined||page==='activity-area')ipcRenderer.send('bigfish:settings',page);},
  onSettingsNavigate:callback=>{const fn=(_e,page)=>{if(page==='activity-area')callback(page);};ipcRenderer.on('bigfish:settings-navigate',fn);return()=>ipcRenderer.removeListener('bigfish:settings-navigate',fn);},
  recall:()=>ipcRenderer.send('bigfish:recall'),
  cancelRecall:()=>ipcRenderer.send('bigfish:cancel-recall'),
  onRecall:callback=>{const fn=()=>callback();ipcRenderer.on('bigfish:recalled',fn);return()=>ipcRenderer.removeListener('bigfish:recalled',fn);},
}));
